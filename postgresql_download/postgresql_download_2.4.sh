        if date.fromisoformat(entry.get('eol', '')) >= today:
            active.append(entry)
    except Exception:
        pass
active.sort(key=lambda e: int(e.get('cycle', '0')), reverse=True)

print(f"  {'메이저':>4}  {'최신버전':<12}  {'지원 종료일':<12}")
